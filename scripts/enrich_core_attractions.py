# 关键词 -> 开放时间覆盖
FREE_KEYWORDS = (
    "街", "路", "广场", "公园", "湖", "海", "滩", "岛", "村", "镇",
    "桥", "长廊", "绿地", "码头", "湾", "江", "山",
)
MUSEUM_KEYWORDS = (
    "博物馆", "纪念馆", "陈列馆", "美术馆", "展览馆", "博物院",
    "旧址", "遗址", "故居", "书院", "天文台", "图书馆",
)


def _price_by_category(category_slug: str, name: str) -> int:
    if category_slug == "theme-park":
        return 25000
    if category_slug == "natural":
        return 0 if _is_free_spot(name) else 8000
    return 0 if _is_free_spot(name) else 5000


def _is_free_spot(name: str) -> bool:
    return any(keyword in name for keyword in FREE_KEYWORDS)


def _hours_by_category(category_slug: str, name: str) -> str:
    if any(keyword in name for keyword in MUSEUM_KEYWORDS):
        return "09:00-17:00（周一闭馆）"
    if _is_free_spot(name):
        return "全天开放"
    if category_slug == "theme-park":
        return "09:30-17:30"
    return "08:00-17:30"


def enrich(record: dict) -> dict:
    name = record["name"]
    city = record["city"]
    if name in REAL_INFO:
        address, phone, price, hours = REAL_INFO[name]
    else:
        address = f"{city}{name}"
        phone = TOURISM_HOTLINE
        price = _price_by_category(record["category_slug"], name)
        hours = _hours_by_category(record["category_slug"], name)
    # 已存在的非空字段保持原值
    record["address"] = record.get("address") or address
    record["phone"] = record.get("phone") or phone
    if record.get("ticket_price_cents") is None:
        record["ticket_price_cents"] = price
    record["opening_hours"] = record.get("opening_hours") or hours
    return record


def main() -> None:
    records = json.loads(DATA_FILE.read_text(encoding="utf-8"))
    enriched = [enrich(record) for record in records]
    missing = [
        record["name"]
        for record in enriched
        if not all(
            [
                record.get("address"),
                record.get("phone"),
                record.get("ticket_price_cents") is not None,
                record.get("opening_hours"),
            ]
        )
    ]
    if missing:
        raise SystemExit(f"字段缺失：{missing[:10]}")
    DATA_FILE.write_text(
        json.dumps(enriched, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    real_count = sum(1 for record in records if record["name"] in REAL_INFO)
    print(f"共补全 {len(enriched)} 条，其中真实信息 {real_count} 条")


if __name__ == "__main__":
    main()
