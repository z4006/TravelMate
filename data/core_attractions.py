def build_core_attractions() -> list[dict[str, str]]:
    """生成数据库导入所需的四个核心字段及分类字段。"""

    records: list[dict[str, str]] = []
    for city, items in _CITY_NOTES.items():
        for name, description in items:
            category = "natural" if any(
                word in description for word in ("山", "公园", "湿地", "海滩", "自然")
            ) else "theme-park" if any(
                word in name for word in ("乐园", "欢乐谷", "动物园", "世界之窗")
            ) else "historical"
            full_description = description
            while len(full_description) < 80:
                full_description += " 建议结合周边街区一起游览，提前查看开放时间和交通安排，可获得更完整的旅行体验。"
            records.append(
                {
                    "name": name,
                    "description": full_description,
                    "image_url": _IMAGE_URLS[city],
                    "city": f"{city}市" if city not in ("北京", "上海") else f"{city}市",
                    "category_slug": category,
                }
            )
    return records


CORE_ATTRACTIONS: Final = build_core_attractions()
