def normalize_city(name: str | None) -> str:
    """把城市名归一化成标准写法；无法识别时原样返回，空值返回空串。"""

    if not name:
        return ""
    value = str(name).strip()
    if not value:
        return ""
    if value in CITY_COORDS:
        return value
    if value in _ALIASES:
        return _ALIASES[value]
    # “北京市市辖区”之类带后缀的写法，取前三个字再试一次
    trimmed = value[:3] + "市"
    if trimmed in CITY_COORDS:
        return trimmed
    return value


def city_coords(name: str | None) -> tuple[float, float] | None:
    """返回城市的 (经度, 纬度)，未收录时返回 None。"""

    key = normalize_city(name)
    return CITY_COORDS.get(key)
